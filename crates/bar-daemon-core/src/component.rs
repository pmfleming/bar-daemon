//! Process ownership. Wire payloads stay versioned by the shared bar-api registry.
use crate::protocol::stream;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Component {
    Bar,
    Notifications,
    Power,
    Compositor,
    Activity,
}
impl Component {
    pub const fn name(self) -> &'static str {
        match self {
            Self::Bar => "bar-daemon",
            Self::Notifications => "bar-notification-daemon",
            Self::Power => "bar-power-daemon",
            Self::Compositor => "bar-compositor-daemon",
            Self::Activity => "bar-activity-daemon",
        }
    }
    pub const fn bus_name(self) -> &'static str {
        match self {
            Self::Bar => "org.laufan.BarStatusDaemon",
            Self::Notifications => "org.laufan.BarNotificationDaemon",
            Self::Power => "org.laufan.BarPowerDaemon",
            Self::Compositor => "org.laufan.BarCompositorDaemon",
            Self::Activity => "org.laufan.BarActivityDaemon",
        }
    }
    // The 4 MiB catalog budget counts decoded strings. JSON escaping can grow
    // those strings sixfold; leave bounded room for fields and the outer record.
    pub(crate) const fn request_bytes(self) -> usize {
        if matches!(self, Self::Bar) {
            32 * 1024 * 1024
        } else {
            1024 * 1024
        }
    }
    pub(crate) fn stream_owner(name: &str) -> Option<Self> {
        Some(match name {
            stream::NOTIFICATIONS | stream::NOTIFICATION_ACTIVE => Self::Notifications,
            stream::BATTERY
            | stream::POWER_PROFILE
            | stream::POWER_SLEEP
            | stream::SLEEP_POLICY => Self::Power,
            stream::WORKSPACES | stream::WORKAREA | stream::COMPOSITOR | stream::DISPLAY_POLICY => {
                Self::Compositor
            }
            stream::ACTIVITY | stream::TIMEZONE => Self::Activity,
            stream::THEME
            | stream::MEDIA
            | stream::AUDIO
            | stream::BRIGHTNESS
            | stream::OSD_HARDWARE
            | stream::UPDATES => Self::Bar,
            _ => return None,
        })
    }
    pub(crate) fn owns_stream(self, name: &str) -> bool {
        Self::stream_owner(name) == Some(self)
    }
    pub(crate) fn owns_method(self, name: &str) -> bool {
        if name == "bar.snapshot" {
            return true;
        }
        if ["notifications."]
            .iter()
            .any(|prefix| name.starts_with(prefix))
        {
            return self == Self::Notifications;
        }
        if ["battery.", "powerProfile.", "powerSleep."]
            .iter()
            .any(|prefix| name.starts_with(prefix))
        {
            return self == Self::Power;
        }
        if [
            "workspace.",
            "displayPolicy.",
            "displayFocus.",
            "displayLayout.",
        ]
        .iter()
        .any(|prefix| name.starts_with(prefix))
        {
            return self == Self::Compositor;
        }
        if ["agenda.", "activity.", "locations.", "location.", "todos."]
            .iter()
            .any(|prefix| name.starts_with(prefix))
        {
            return self == Self::Activity;
        }
        self == Self::Bar
    }
    pub(crate) fn streams(self) -> Vec<&'static str> {
        crate::protocol::STREAMS
            .iter()
            .copied()
            .filter(|s| self.owns_stream(s))
            .collect()
    }
}

/// Generate the frontend's process ownership table from the live Rust registry.
pub fn routing_javascript() -> String {
    let components = [
        Component::Bar,
        Component::Notifications,
        Component::Power,
        Component::Compositor,
        Component::Activity,
    ];
    let mut streams = serde_json::Map::new();
    for component in components {
        streams.insert(
            component.name().into(),
            serde_json::json!(component.streams()),
        );
    }
    let projection_owners: serde_json::Map<String, serde_json::Value> = crate::protocol::STREAMS
        .iter()
        .map(|stream| {
            let spec =
                crate::protocol::read_wire::stream_spec(stream).expect("registered projection");
            (
                spec.snapshot_key.into(),
                serde_json::json!(
                    Component::stream_owner(stream)
                        .expect("registered owner")
                        .name()
                ),
            )
        })
        .collect();
    format!(
        ".pragma library\n// Generated by bar-daemon debug routing-javascript. Do not edit.\nvar daemons = {};\nvar streamsByDaemon = {};\nvar projections = {};\nfunction daemonForStream(stream) {{\n    for (var daemon in streamsByDaemon) if (streamsByDaemon[daemon].includes(stream)) return daemon;\n    return \"\";\n}}\nfunction daemonForProjection(projection) {{ return projections[projection] || \"\"; }}\nfunction selectStreams(streams, daemon) {{\n    return Array.from(streams).filter(function(stream) {{ return daemonForStream(stream) === daemon; }});\n}}\n",
        serde_json::to_string(&components.map(Component::name)).unwrap(),
        serde_json::to_string_pretty(&streams).unwrap(),
        serde_json::to_string_pretty(&projection_owners).unwrap()
    )
}

/// Default diagnostics for owned implementation/provider crates only.
pub fn default_log_filter() -> &'static str {
    "bar_daemon=info,bar_daemon_core=info,bar_audio_native=info,bar_power_events=info,bar_sharing_native=info,shelllist_daemon_tokio=info,shelllist_hyprland=info"
}

/// Entrypoint shared by the component executables. Each has its own endpoint.
pub async fn main<F>(component: Component, run: fn() -> F) -> anyhow::Result<()>
where
    F: std::future::Future<Output = anyhow::Result<()>>,
{
    use clap::{CommandFactory, FromArgMatches, Parser, Subcommand};
    use std::io::IsTerminal;
    #[derive(Parser)]
    #[command(version)]
    struct Args {
        #[command(subcommand)]
        command: Command,
    }
    #[derive(Subcommand)]
    enum Command {
        Daemon,
        Client,
    }
    tracing_subscriber::fmt()
        .with_writer(std::io::stderr)
        .with_ansi(std::io::stderr().is_terminal())
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| default_log_filter().into()),
        )
        .init();
    let args = Args::from_arg_matches(&Args::command().name(component.name()).get_matches())?;
    match args.command {
        Command::Daemon => run().await,
        Command::Client => crate::client::run_component(component).await,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn streams_have_one_process_owner() {
        assert_eq!(
            routing_javascript(),
            include_str!("../../../test_support/bar-routing.js")
        );
        assert_eq!(Component::stream_owner("new-domain.changed"), None);
        assert!(!Component::Bar.owns_stream("new-domain.changed"));
        for stream in crate::protocol::STREAMS {
            assert_eq!(
                [
                    Component::Bar,
                    Component::Notifications,
                    Component::Power,
                    Component::Compositor,
                    Component::Activity
                ]
                .iter()
                .filter(|c| c.owns_stream(stream))
                .count(),
                1,
                "{stream}"
            );
        }
        for method in crate::protocol::METHODS
            .iter()
            .filter(|m| **m != "bar.snapshot")
        {
            assert_eq!(
                [
                    Component::Bar,
                    Component::Notifications,
                    Component::Power,
                    Component::Compositor,
                    Component::Activity
                ]
                .iter()
                .filter(|c| c.owns_method(method))
                .count(),
                1,
                "{method}"
            );
        }
        assert!(!Component::Bar.owns_method("notifications.invoke"));
        assert!(!Component::Notifications.owns_method("powerSleep.request"));
    }
    #[tokio::test]
    async fn component_snapshots_and_calls_reject_foreign_domains() {
        for component in [
            Component::Bar,
            Component::Notifications,
            Component::Power,
            Component::Compositor,
            Component::Activity,
        ] {
            let state = crate::state::StateStore::for_component(component);
            let api = crate::api::ApiService::new(
                state.clone(),
                None,
                crate::activity::notifications::service::NotificationService::remote(),
                crate::media::MediaService::default(),
                crate::brightness::BrightnessService::new(state.clone()),
            );
            let value = api.dispatch("bar.snapshot", serde_json::json!({})).await;
            let keys = value["data"]["snapshot"].as_object().unwrap();
            assert_eq!(keys.len(), component.streams().len());
            assert_eq!(
                keys.contains_key("notifications"),
                component == Component::Notifications
            );
            let foreign = if component == Component::Notifications {
                "battery.changed"
            } else {
                "notifications.changed"
            };
            assert_eq!(
                api.dispatch("bar.snapshot", serde_json::json!({"streams":[foreign]}))
                    .await["ok"],
                false
            );
        }
    }
}
